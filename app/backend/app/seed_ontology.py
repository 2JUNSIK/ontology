"""녹조 관리 / 수질오염 대응 도메인 가이드 (PLAN.md §8).

용도: `claude_extractor.py`(N3)의 추출 프롬프트 **안정 프리픽스**로 `DOMAIN_GUIDE`를
사용한다(prompt caching 대상). 실무 임계값·모델링 가이드가 여기 포함된다.

주의: 이 가이드는 '출발점'이지 정답이 아니다. 실제 지식그래프는 직원의 자연어 입력 +
Claude 추출 + 사용자 편집으로 확정된다.
"""

from __future__ import annotations

# ------------------------------------------------------------------
# 수질 항목(관측 지표)과 단위 — 도메인 가이드 상수
# ------------------------------------------------------------------
WATER_QUALITY_ITEMS: list[tuple[str, str]] = [
    ("클로로필-a", "μg/L"),
    ("남조류세포수", "cells/mL"),
    ("T-P", "mg/L"),   # 총인
    ("T-N", "mg/L"),   # 총질소
    ("DO", "mg/L"),    # 용존산소
    ("수온", "℃"),
    ("pH", "-"),
    ("COD", "mg/L"),
    ("BOD", "mg/L"),
]

# 조류경보제 단계(남조류세포수 기준, cells/mL)
ALGAE_ALERT_THRESHOLDS: dict[str, int] = {
    "관심": 1_000,
    "경계": 10_000,
    "대발생": 1_000_000,
}


def _threshold_line() -> str:
    parts = [f"{k} ≥ {v:,} cells/mL" for k, v in ALGAE_ALERT_THRESHOLDS.items()]
    return " / ".join(parts)


# ------------------------------------------------------------------
# 표준 타입/관계 어휘 (N9) — LLM 자유생성 억제 + 후처리 정규화의 기준
# ------------------------------------------------------------------
# 엔티티 타입 표준 집합(수자원 운영관리). 추출은 이 목록에서 고르도록 '유도'하되,
# 비표준 타입도 관대하게 통과시킨다(도메인 확장성). 정규화/검증은 ontology_normalizer가 담당.
STANDARD_ENTITY_TYPES: list[str] = [
    "저수지", "하천", "댐", "측정소", "시설",
    "수질항목", "수문항목", "측정값",
    "생물", "현상", "제도", "경보단계",
    "오염원", "대응조치", "기관", "지표",
]

# 관계타입 표준 집합.
STANDARD_RELATION_TYPES: list[str] = [
    "원인", "단계", "기준지표", "유입", "관할",
    "측정", "위치", "대응", "포함", "발령",
]

# 비표준 타입 동의어 → 표준 타입(명백한 표기 변형만 보수적으로 — 오탐 방지).
TYPE_ALIASES: dict[str, str] = {
    "관측소": "측정소",
    "계측소": "측정소",
    "취수장": "시설",
    "정수장": "시설",
    "호소": "저수지",
    "호수": "저수지",
}

# 엔티티 별칭·약어 → 표준명(canonical). 표준명은 WATER_QUALITY_ITEMS 표기와 정합시킨다
# (예: "총인"→"T-P"). 방향·규모는 상수라 나중에 조정하기 쉽다.
CANONICAL_ALIASES: dict[str, str] = {
    "총인": "T-P",
    "총질소": "T-N",
    "용존산소": "DO",
    "수소이온농도": "pH",
    "화학적산소요구량": "COD",
    "생물화학적산소요구량": "BOD",
    "생물학적산소요구량": "BOD",
    "시아노박테리아": "남조류",
    "남조류세포": "남조류세포수",
    "조류대발생": "녹조",
    "클로로필a": "클로로필-a",
    "클로로필A": "클로로필-a",
}

# 관계타입 → (허용 source 타입 집합, 허용 target 타입 집합). domain/range 제약.
# 방향·타입이 명확한 것만 '보수적으로' 둔다(경고 오탐 방지). 여기 없는 관계타입은
# validate_domain_range에서 통과시킨다.
RELATION_CONSTRAINTS: dict[str, tuple[set[str], set[str]]] = {
    "단계": ({"제도"}, {"경보단계"}),
    "기준지표": ({"경보단계"}, {"수질항목", "지표"}),
    "유입": ({"오염원"}, {"저수지", "하천", "댐"}),
    "관할": ({"기관"}, {"저수지", "하천", "댐", "측정소", "시설"}),
    "측정": ({"측정소"}, {"수질항목", "수문항목", "지표", "측정값"}),
}


def _standard_vocab_block() -> str:
    """표준 타입/관계·domain-range·별칭 지시를 프롬프트 문자열로 직렬화(캐시 프리픽스용)."""
    types = ", ".join(STANDARD_ENTITY_TYPES)
    rels = ", ".join(STANDARD_RELATION_TYPES)
    dr = "\n".join(
        f"  - {rt}: ({'/'.join(sorted(src))}) → ({'/'.join(sorted(tgt))})"
        for rt, (src, tgt) in RELATION_CONSTRAINTS.items()
    )
    alias = ", ".join(f"{a}→{c}" for a, c in CANONICAL_ALIASES.items())
    return (
        "표준 엔티티 타입(가능하면 이 목록에서 선택):\n  " + types + "\n"
        "표준 관계타입(가능하면 이 목록에서 선택):\n  " + rels + "\n"
        "관계 방향 규칙(domain → range; 위반이 의심되면 타입을 재검토):\n" + dr + "\n"
        "엔티티 이름 표기 통일(약어/동의어 → 표준명): " + alias
    )


# Claude 추출 프롬프트의 안정 프리픽스로 쓰이는 도메인 모델링 가이드(prompt caching 대상).
DOMAIN_GUIDE: str = f"""\
[도메인: K-water 녹조 관리 / 수질오염 대응 온톨로지 모델링 가이드]

핵심 개념(노드): 저수지, 측정소, 수질항목, 측정값, 조류경보, 오염원, 대응조치, 기관.

모델링 원칙:
- 측정값은 (측정소 × 수질항목 × 측정시각)을 잇는 **별도 이벤트 노드**로 분리한다.
  값을 측정소나 항목의 속성으로 넣지 말 것(시계열/다대다 표현 불가해짐).
- 조류경보는 발령 이벤트 노드로 두고, 근거지표(예: 남조류세포수)와 연결한다.
- 각 개념의 식별 속성(key)을 정하고 UNIQUE 제약을 부여할 것(예: 측정소=측정소코드).

조류경보제 단계(남조류세포수 기준): {_threshold_line()}.

수질 항목·단위 예시: {", ".join(f"{n}({u})" for n, u in WATER_QUALITY_ITEMS)}.

[표준 어휘 — 일관성 유지]
{_standard_vocab_block()}
"""
